/// Looks up a UI string. Falls back to English, then to the key itself.
/// `{name}` placeholders are replaced from [params].
String t(String key, {Lang? lang, Map<String, String>? params}) {
  final l = lang ?? LangService.current.value;
  final map = l == Lang.si ? stringsSi : stringsEn;
  var value = map[key] ?? stringsEn[key] ?? key;
  params?.forEach((name, replacement) {
    value = value.replaceAll('{$name}', replacement);
  });
  return value;
}
